-- 1. New UUID id per entity row
-- Built by hand (not uuidv7()): Postgres keeps uuidv7() monotonic per session, which would
-- follow the physical row order instead of the old id order. Each row gets its own millisecond.
ALTER TABLE users ADD COLUMN new_id uuid;
UPDATE users SET new_id = (lpad(to_hex(m.now_ms - (m.max_id - users.id)), 12, '0') || '7' || substr(md5(random()::text), 1, 3) || substr('89ab', floor(random() * 4)::int + 1, 1) || substr(md5(random()::text), 1, 15))::uuid FROM (SELECT max(id) AS max_id, (extract(epoch FROM clock_timestamp()) * 1000)::bigint AS now_ms FROM users) m;
